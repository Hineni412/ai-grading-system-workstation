@lru_cache(maxsize=1)
def _attribute_definitions() -> dict[str, dict[str, Any]]:
    definitions = {}
    for line in filter(str.strip, _ROWS.strip().splitlines()):
        name, definition, include, exclude, anchor = line.split("|")
        if name in definitions:
            raise ValueError(f"duplicate attribute definition: {name}")
        definitions[name] = {"definition": definition, "include_scope": include,
                             "exclude_scope": exclude, "anchors": [anchor]}
    return definitions


def definition_for_attribute(name: str) -> dict[str, Any]:
    return copy.deepcopy(_attribute_definitions().get(name, {}))


def enrich_attribute_definitions(catalog: Mapping[str, Any]) -> dict[str, Any]:
    definitions = _attribute_definitions()
    result = copy.deepcopy(dict(catalog))
    found = set()
    for term in result["terms"]:
        if term["dimension"] not in {"ability", "thought", "method", "model", "special_type"}:
            continue
        name = str(term["name"])
        if name not in definitions:
            raise ValueError(f"missing attribute definition: {name}")
        term.update(definitions[name])
        found.add(name)
    if found != set(definitions):
        raise ValueError("attribute definitions do not match the governed catalog")
    return result